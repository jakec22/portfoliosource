export function searchFoods(query: string): Food[] {
  const q = query.toLowerCase().trim();
  if (!q) return COMMON_FOODS;
  return COMMON_FOODS.filter(
    (f) =>
      f.name.toLowerCase().includes(q) ||
      (f.brand && f.brand.toLowerCase().includes(q))
  );
}
